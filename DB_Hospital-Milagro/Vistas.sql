--15. Doctores con Mayor Número de Citas Atendidas


CREATE OR REPLACE VIEW V_DOCTORES_TOP_CITAS AS
SELECT 
    D.ID_DOCTOR,
    U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS DOCTOR,
    E.NOMBRE AS ESPECIALIDAD,
    COUNT(C.ID_CITA) AS TOTAL_CITAS_ATENDIDAS,
    ROUND(COUNT(C.ID_CITA) * 100.0 / (SELECT COUNT(*) FROM FIDE_CITAS_TB), 2) AS PORCENTAJE
FROM 
    FIDE_DOCTORES_TB D
JOIN 
    FIDE_USUARIOS_TB U ON D.ID_USUARIO = U.ID_USUARIO
JOIN 
    FIDE_CITAS_TB C ON D.ID_DOCTOR = C.ID_DOCTOR
JOIN 
    FIDE_DOCTORES_ESPECIALIDADES_TB DE ON D.ID_DOCTOR = DE.ID_DOCTOR
JOIN 
    FIDE_ESPECIALIDADES_TB E ON DE.ID_ESPECIALIDAD = E.ID_ESPECIALIDAD
WHERE 
    C.ID_ESTADO_CITA = (SELECT ID_ESTADO_CITA FROM FIDE_ESTADOS_CITAS_TB WHERE NOMBRE_ESTADO = 'COMPLETADA') -- Ajustar según valores reales
GROUP BY 
    D.ID_DOCTOR, U.NOMBRE, U.PRIMER_APELLIDO, E.NOMBRE
ORDER BY 
    TOTAL_CITAS_ATENDIDAS DESC;
    
    
--16.  Pacientes con Tratamientos por Vencer 


CREATE OR REPLACE VIEW V_TRATAMIENTOS_POR_VENCER AS
SELECT 
    P.ID_PACIENTE,
    U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS PACIENTE,
    T.ID_TRATAMIENTO,
    T.DESCRIPCION AS TRATAMIENTO,
    T.FECHA_FIN,
    TRUNC(T.FECHA_FIN - SYSDATE) AS DIAS_RESTANTES
FROM 
    FIDE_PACIENTES_TB P
JOIN 
    FIDE_USUARIOS_TB U ON P.ID_USUARIO = U.ID_USUARIO
JOIN 
    FIDE_TRATAMIENTOS_TB T ON P.ID_PACIENTE = T.ID_PACIENTE
WHERE 
    T.FECHA_FIN BETWEEN SYSDATE AND SYSDATE + 30
    AND T.ACTIVO = 1;
    
    
--17. Disponibilidad de Consultorios por Especialidad

CREATE OR REPLACE VIEW V_CONSULTORIOS_ESPECIALIDAD AS
SELECT 
    E.ID_ESPECIALIDAD,
