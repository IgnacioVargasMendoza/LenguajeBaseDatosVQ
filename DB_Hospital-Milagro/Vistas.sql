--12.  Resumen de Pagos por Paciente

CREATE OR REPLACE VIEW V_RESUMEN_PAGOS_PACIENTE AS
SELECT 
    P.ID_PACIENTE,
    U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS PACIENTE,
    COUNT(F.ID_FACTURA) AS TOTAL_FACTURAS,
    SUM(F.MONTO_TOTAL) AS MONTO_TOTAL,
    MIN(F.FECHA_EMISION) AS PRIMER_PAGO,
    MAX(F.FECHA_EMISION) AS ULTIMO_PAGO
FROM 
    FIDE_PACIENTES_TB P
JOIN 
    FIDE_USUARIOS_TB U ON P.ID_USUARIO = U.ID_USUARIO
LEFT JOIN 
    FIDE_FACTURAS_TB F ON P.ID_PACIENTE = F.ID_PACIENTE
GROUP BY 
    P.ID_PACIENTE, U.NOMBRE, U.PRIMER_APELLIDO;
    
    
