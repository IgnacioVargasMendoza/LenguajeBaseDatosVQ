    USR_PAC.NOMBRE || ' ' || USR_PAC.PRIMER_APELLIDO AS NOMBRE_PACIENTE,
    CC.MONTO AS COSTO,
    CC.DESCRIPCION AS DETALLE_COSTO
FROM 
    FIDE_CITAS_TB C
JOIN 
    FIDE_ESTADOS_CITAS_TB EC ON C.ID_ESTADO_CITA = EC.ID_ESTADO_CITA
JOIN 
    FIDE_DOCTORES_TB D ON C.ID_DOCTOR = D.ID_DOCTOR
JOIN 
    FIDE_USUARIOS_TB USR_DOC ON D.ID_USUARIO = USR_DOC.ID_USUARIO
JOIN 
    FIDE_PACIENTES_TB P ON C.ID_PACIENTE = P.ID_PACIENTE
JOIN 
    FIDE_USUARIOS_TB USR_PAC ON P.ID_USUARIO = USR_PAC.ID_USUARIO
LEFT JOIN 
    FIDE_COSTOS_CITA_TB CC ON CC.ID_CITA = C.ID_CITA;
    
    
    
--3. Vista Resumen de Costos por Doctor


CREATE OR REPLACE VIEW V_RESUMEN_COSTOS_DOCTOR AS
SELECT 
    D.ID_DOCTOR,
    USR_DOC.NOMBRE || ' ' || USR_DOC.PRIMER_APELLIDO AS NOMBRE_DOCTOR,
    COUNT(C.ID_CITA) AS TOTAL_CITAS,
    NVL(SUM(CC.MONTO), 0) AS INGRESOS_TOTALES
FROM 
    FIDE_DOCTORES_TB D
JOIN 
    FIDE_USUARIOS_TB USR_DOC ON D.ID_USUARIO = USR_DOC.ID_USUARIO
LEFT JOIN 
    FIDE_CITAS_TB C ON D.ID_DOCTOR = C.ID_DOCTOR
LEFT JOIN 
    FIDE_COSTOS_CITA_TB CC ON CC.ID_CITA = C.ID_CITA
GROUP BY 
    D.ID_DOCTOR, USR_DOC.NOMBRE, USR_DOC.PRIMER_APELLIDO;
    
    
    
--4. Vista Detalle de Facturación con Citas 

CREATE OR REPLACE VIEW V_DETALLE_FACTURA_CITAS AS
SELECT 
    F.ID_FACTURA,
    C.ID_CITA,
    C.FECHA AS FECHA_CITA,
    D.ID_DOCTOR,
    USR_DOC.NOMBRE || ' ' || USR_DOC.PRIMER_APELLIDO AS DOCTOR,
    CC.MONTO AS COSTO_CITA,
    F.MONTO_TOTAL AS MONTO_FACTURA
FROM 
    FIDE_FACTURAS_TB F
JOIN 
    FIDE_PACIENTES_TB P ON F.ID_PACIENTE = P.ID_PACIENTE
JOIN 
    FIDE_CITAS_TB C ON C.ID_PACIENTE = P.ID_PACIENTE
JOIN 
    FIDE_DOCTORES_TB D ON C.ID_DOCTOR = D.ID_DOCTOR
JOIN 
    FIDE_USUARIOS_TB USR_DOC ON D.ID_USUARIO = USR_DOC.ID_USUARIO
LEFT JOIN 
    FIDE_COSTOS_CITA_TB CC ON CC.ID_CITA = C.ID_CITA
WHERE 
    C.FECHA BETWEEN F.FECHA_EMISION AND NVL(F.FECHA_VENCIMIENTO, SYSDATE);
    
    
    
--5. Pacientes con Tratamientos Activos

