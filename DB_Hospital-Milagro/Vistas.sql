--8.  Medicamentos en Inventario

CREATE OR REPLACE VIEW V_MEDICAMENTOS_BAJO_STOCK AS
SELECT 
    M.ID_MEDICAMENTO,
    M.NOMBRE AS MEDICAMENTO,
    I.CANTIDAD,
    M.PRECIO,
    CASE 
        WHEN I.CANTIDAD < 10 THEN 'CRÍTICO'
        WHEN I.CANTIDAD BETWEEN 10 AND 20 THEN 'BAJO'
        ELSE 'SUFICIENTE'
    END AS ESTADO_STOCK
FROM 
    FIDE_MEDICAMENTOS_TB M
JOIN 
    FIDE_INVENTARIO_MEDICAMENTOS_TB I ON M.ID_MEDICAMENTO = I.ID_MEDICAMENTO
WHERE 
    I.CANTIDAD < 20 -- Umbral ajustable
    AND I.ACTIVO = 1;
    
    
    
--9.Historial de Cambios de Estado en Citas

CREATE OR REPLACE VIEW V_HISTORIAL_ESTADOS_CITAS AS
SELECT 
    HC.ID_HISTORIAL,
    C.ID_CITA,
    EC_ANT.NOMBRE_ESTADO AS ESTADO_ANTERIOR,
    EC_NUEVO.NOMBRE_ESTADO AS ESTADO_NUEVO,
    HC.FECHA_CAMBIO,
    HC.OBSERVACIONES
FROM 
    FIDE_HISTORIAL_CITAS_TB HC
JOIN 
    FIDE_CITAS_TB C ON HC.ID_CITA = C.ID_CITA
LEFT JOIN 
    FIDE_ESTADOS_CITAS_TB EC_ANT ON HC.ID_ESTADO_ANTERIOR = EC_ANT.ID_ESTADO_CITA
LEFT JOIN 
    FIDE_ESTADOS_CITAS_TB EC_NUEVO ON HC.ID_ESTADO_NUEVO = EC_NUEVO.ID_ESTADO_CITA
ORDER BY 
    HC.FECHA_CAMBIO DESC;
    
    
--10.Disponibilidad de Doctores por Día

CREATE OR REPLACE VIEW V_DISPONIBILIDAD_DOCTORES AS
SELECT 
    D.ID_DOCTOR,
    U.NOMBRE || ' ' || U.PRIMER_APELLIDO AS DOCTOR,
    DIS.DIA,
    TO_CHAR(DIS.HORA_INICIO, 'HH24:MI') AS HORA_INICIO,
    TO_CHAR(DIS.HORA_FIN, 'HH24:MI') AS HORA_FIN
FROM 
    FIDE_DISPONIBILIDAD_TB DIS
JOIN 
    FIDE_DOCTORES_TB D ON DIS.ID_DOCTOR = D.ID_DOCTOR
JOIN 
    FIDE_USUARIOS_TB U ON D.ID_USUARIO = U.ID_USUARIO
WHERE 
    DIS.ACTIVO = 1
ORDER BY 
    D.ID_DOCTOR, DIS.DIA;
    
    
    
--11.   Procedimientos Más Comunes en Tratamientos

