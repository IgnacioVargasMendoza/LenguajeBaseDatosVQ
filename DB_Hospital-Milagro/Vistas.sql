    D.ACTIVO = 1;
    
--18.  Eficiencia en Uso de Medicamentos

CREATE OR REPLACE VIEW V_EFICIENCIA_MEDICAMENTOS AS
SELECT 
    M.ID_MEDICAMENTO,
    M.NOMBRE AS MEDICAMENTO,
    COUNT(DISTINCT TM.ID_TRATAMIENTO) AS TOTAL_TRATAMIENTOS,
    COUNT(DISTINCT P.ID_PACIENTE) AS PACIENTES_ATENDIDOS,
    SUM(M.PRECIO) AS INGRESOS_GENERADOS,
    ROUND(SUM(M.PRECIO) / NULLIF(COUNT(DISTINCT P.ID_PACIENTE), 0), 2) AS COSTO_POR_PACIENTE
FROM 
    FIDE_MEDICAMENTOS_TB M
JOIN 
    FIDE_TRATAMIENTOS_MEDICAMENTOS_TB TM ON M.ID_MEDICAMENTO = TM.ID_MEDICAMENTO
JOIN 
    FIDE_TRATAMIENTOS_TB T ON TM.ID_TRATAMIENTO = T.ID_TRATAMIENTO
JOIN 
    FIDE_PACIENTES_TB P ON T.ID_PACIENTE = P.ID_PACIENTE
GROUP BY 
    M.ID_MEDICAMENTO, M.NOMBRE;
