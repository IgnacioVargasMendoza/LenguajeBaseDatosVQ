BEGIN
  FOR obj IN (SELECT object_name, object_type FROM user_objects WHERE object_type IN ('TABLE','VIEW','PACKAGE','PROCEDURE','FUNCTION','SEQUENCE','SYNONYM','MATERIALIZED VIEW')) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP ' || obj.object_type || ' ' || obj.object_name || 
                        CASE WHEN obj.object_type = 'TABLE' THEN ' CASCADE CONSTRAINTS PURGE' ELSE '' END;
    EXCEPTION
      WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Error al eliminar: ' || obj.object_type || ' ' || obj.object_name);
    END;
  END LOOP;
END;

